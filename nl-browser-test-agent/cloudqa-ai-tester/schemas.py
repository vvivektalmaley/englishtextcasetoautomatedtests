from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field, ConfigDict


class ActionType(str, Enum):
    CLICK = "click"
    TYPE = "type"
    SELECT = "select"
    ASSERT_TEXT = "assert_text"
    ASSERT_URL = "assert_url"
    WAIT = "wait"
    PRESS_ENTER = "press_enter"


class TestStep(BaseModel):
    """
    One action or assertion in a test plan.
    """

    model_config = ConfigDict(extra="forbid")

    action: ActionType

    # Human-readable target, e.g. "email input field"
    element_description: Optional[str] = None

    # Text to enter or option to select
    value: Optional[str] = None

    # Text expected to appear on the page
    expected_text: Optional[str] = None

    # URL fragment or full URL expected
    expected_url: Optional[str] = None

    # Timeout for wait/assertion
    timeout_seconds: int = Field(default=10, ge=1, le=60)

    # Why this step exists
    reasoning: str = ""


class TestPlan(BaseModel):
    """
    Complete test plan generated by Groq.
    """

    model_config = ConfigDict(extra="forbid")

    test_name: str

    description: str

    steps: list[TestStep] = Field(
        min_length=1,
        max_length=30,
    )


class StepResult(BaseModel):
    """
    Execution result for an individual step.
    """

    step_number: int

    action: str

    description: str

    status: str

    message: str

    duration_seconds: float = 0.0

    screenshot: Optional[str] = None


class TestReport(BaseModel):
    """
    Overall test execution report.
    """

    test_name: str

    status: str

    total_steps: int

    passed_steps: int

    failed_steps: int

    results: list[StepResult]
